/**
 * Maps a numeric score and maxMarks to the official Alphabet Grade
 */
export function getAlphabetGrade(score, maxMarks) {
  if (score == null || maxMarks == null || maxMarks <= 0) return null;
  const percent = (score / maxMarks) * 100;

  if (percent >= 90) {
    return {
      grade: 'O',
      point: 10,
      label: 'Outstanding',
      fullBadge: 'O = 10 (Outstanding)',
      percent: percent.toFixed(1),
      isRedo: false,
      badgeClass: 'bg-emerald-50 text-emerald-800 border-emerald-300',
    };
  }
  if (percent >= 80) {
    return {
      grade: 'A+',
      point: 9,
      label: 'Excellent',
      fullBadge: 'A+ = 9 (Excellent)',
      percent: percent.toFixed(1),
      isRedo: false,
      badgeClass: 'bg-teal-50 text-teal-800 border-teal-300',
    };
  }
  if (percent >= 70) {
    return {
      grade: 'A',
      point: 8,
      label: 'Very Good',
      fullBadge: 'A = 8 (Very Good)',
      percent: percent.toFixed(1),
      isRedo: false,
      badgeClass: 'bg-blue-50 text-blue-800 border-blue-300',
    };
  }
  if (percent >= 60) {
    return {
      grade: 'B+',
      point: 7,
      label: 'Good',
      fullBadge: 'B+ = 7 (Good)',
      percent: percent.toFixed(1),
      isRedo: false,
      badgeClass: 'bg-indigo-50 text-indigo-800 border-indigo-300',
    };
  }
  if (percent >= 55) {
    return {
      grade: 'B',
      point: 6,
      label: 'Above Average',
      fullBadge: 'B = 6 (Above Average)',
      percent: percent.toFixed(1),
      isRedo: false,
      badgeClass: 'bg-amber-50 text-amber-800 border-amber-300',
    };
  }
  if (percent >= 50) {
    return {
      grade: 'C',
      point: 5,
      label: 'Pass',
      fullBadge: 'C = 5 (Pass)',
      percent: percent.toFixed(1),
      isRedo: false,
      badgeClass: 'bg-orange-50 text-orange-800 border-orange-300',
    };
  }
  return {
    grade: 'F',
    point: 0,
    label: 'REDO / FAIL',
    fullBadge: 'F = REDO/FAIL',
    percent: percent.toFixed(1),
    isRedo: true,
    badgeClass: 'bg-red-50 text-[#DC2626] border-red-300',
  };
}

