// Flattened universal search index across buildings, floors, rooms, facilities, departments & lab keywords
export function getUniversalSearchIndex() {
  const index = [];

  CAMPUS_BUILDING_NODES.forEach((bld) => {
    // 1. Building entries
    index.push({
      type: 'building',
      id: bld.id,
      code: bld.code,
      title: bld.name,
      subtitle: `${bld.sector} • ${bld.floorsCount} Floors`,
      category: 'Building',
      buildingId: bld.id,
      buildingCode: bld.code,
      buildingName: bld.name,
      floorNumber: bld.defaultFloor,
      floorName: `${bld.defaultFloor === 0 ? 'Ground' : bld.defaultFloor + 'th'} Floor`,
      departments: bld.departments,
      keywords: [bld.code, bld.name, bld.shortName, ...bld.departments, ...bld.features],
    });

    // 2. Department entries for building
    bld.departments.forEach((dept) => {
      index.push({
        type: 'department',
        id: `dept-${bld.code}-${dept.replace(/\s+/g, '-').toLowerCase()}`,
        code: bld.code,
        title: dept,
        subtitle: `Housed inside ${bld.name} (${bld.code})`,
        category: 'Department',
        buildingId: bld.id,
        buildingCode: bld.code,
        buildingName: bld.name,
        floorNumber: bld.defaultFloor,
        floorName: `${bld.defaultFloor === 0 ? 'Ground' : bld.defaultFloor + 'th'} Floor`,
        departments: [dept],
        keywords: [dept, bld.code, bld.name],
      });
    });

    // 3. Room & Lab entries
    const floors = INDOOR_FLOOR_PLANS[bld.id] || {};
    Object.values(floors).forEach((floor) => {
      floor.rooms.forEach((room) => {
        index.push({
          type: 'room',
          id: room.id,
          code: room.code,
          title: `${room.code}: ${room.name}`,
          subtitle: `${bld.name} • ${floor.floorName} (${room.type})`,
          category: room.type,
          buildingId: bld.id,
          buildingCode: bld.code,
          buildingName: bld.name,
          floorNumber: floor.floorNumber,
          floorName: floor.floorName,
          room: room,
          departments: [room.department],
          keywords: [
            room.code,
            room.code.replace('-', ''),
            room.code.split('-')[1] || '',
            room.name,
            room.type,
            room.department,
            bld.code,
            bld.name,
            ...(room.facilities || []),
            room.nearbyLandmark,
          ],
        });
      });
    });
  });

  return index;
}

// Search helper function
export function searchCampusCatalog(query) {
  if (!query || typeof query !== 'string') return [];
  const q = query.trim().toLowerCase();
  const normalizedNum = q.replace(/[^0-9a-z]/g, '');

  const index = getUniversalSearchIndex();

  return index
    .filter((item) => {
      const titleMatch = item.title.toLowerCase().includes(q);
      const codeMatch = item.code.toLowerCase().includes(q) || item.code.toLowerCase().replace('-', '').includes(normalizedNum);
      const subtitleMatch = item.subtitle.toLowerCase().includes(q);
      const keywordMatch = item.keywords.some((k) => k.toLowerCase().includes(q) || k.toLowerCase().replace(/[^0-9a-z]/g, '').includes(normalizedNum));

      return titleMatch || codeMatch || subtitleMatch || keywordMatch;
    })
    .slice(0, 10);
}

// Direction generation helper: produces actual step-by-step navigation instructions
export function generateDirections({ startPoint, building, floor, room }) {
  if (!building || !room) return null;

  const steps = [];
  let estimatedTime = '3 mins';
  let distance = '85 meters';

  const startLabels = {
    campus_gate: 'North Main Campus Gate',
    building_entrance: `${building.name} Main Entrance (Ground Floor)`,
    staircase: 'West Wing Staircase',
    elevator: 'Central High-Speed Elevator',
  };

  const startName = startLabels[startPoint] || startLabels.building_entrance;

  if (startPoint === 'campus_gate') {
    steps.push(`Start at ${startName} and follow Central Spine Boulevard south toward ${building.sector}.`);
    steps.push(`Walk past the North Academic Lawn and approach ${building.name} (${building.code}).`);
    steps.push(`Enter through ${building.map.entrance.label} on the ground level.`);
    estimatedTime = '5 mins';
    distance = '210 meters';
  } else if (startPoint === 'building_entrance') {
    steps.push(`Enter ${building.name} via ${building.map.entrance.label}.`);
    estimatedTime = `${Math.max(2, floor.floorNumber * 1 + 2)} mins`;
    distance = `${45 + floor.floorNumber * 20} meters`;
  }

  // Vertical movement if room is above Ground Floor
  if (floor.floorNumber > 0) {
    if (startPoint === 'staircase') {
      steps.push(`From the Ground Floor, take the West Staircase up to ${floor.floorName}.`);
    } else if (startPoint === 'elevator') {
      steps.push(`Step into the Central Elevator and press button for Floor ${floor.floorNumber}.`);
    } else {
      steps.push(`Head through the main foyer to the Central Elevator or West Staircase and proceed to ${floor.floorName}.`);
    }
  }

  // Indoor hallway directions
  steps.push(`Exit into the main corridor on ${floor.floorName}.`);
  if (room.nearbyLandmark) {
    steps.push(`Walk along the corridor toward ${room.nearbyLandmark}.`);
  }
  steps.push(`Arrive at ${room.code} (${room.name}) on your ${room.door.x > 350 ? 'right' : 'left'}. Scan RFID card or enter directly.`);

  return {
    startPoint: startName,
    destination: `${room.code} • ${room.name}`,
    buildingName: building.name,
    floorName: floor.floorName,
    estimatedTime,
    distance,
    steps,
  };
}
